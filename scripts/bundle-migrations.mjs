#!/usr/bin/env node
// Concatenates supabase/migrations/*.sql, in filename order, into
// supabase/all_migrations.sql: one script that builds a fresh database in a
// single transaction. Run `npm run db:bundle` after adding a migration; pass
// --check to fail (e.g. in CI) when the bundle is out of date.
import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const migrationsDir = join(root, 'supabase', 'migrations')
const bundlePath = join(root, 'supabase', 'all_migrations.sql')

const files = readdirSync(migrationsDir).filter((name) => /^\d{4}_[a-z0-9_]+\.sql$/.test(name)).sort()
const numbers = files.map((name) => name.slice(0, 4))
const duplicate = numbers.find((n, i) => numbers.indexOf(n) !== i)
if (duplicate) {
  console.error(`Two migrations share number ${duplicate}; renumber one so the order is unambiguous.`)
  process.exit(1)
}

const sections = files.map((name) => {
  const sql = readFileSync(join(migrationsDir, name), 'utf8').trimEnd()
  return `-- >>> ${name}\n${sql}\n`
})

const bundle = [
  '-- GENERATED by `npm run db:bundle` from supabase/migrations. Do not edit by hand:',
  '-- add a new numbered file there and re-run the script, which appends it here.',
  '-- Runs every migration once, in order, on a fresh Supabase database. Any error',
  '-- rolls the whole run back.',
  '',
  'begin;',
  '',
  sections.join('\n'),
  'commit;',
  '',
].join('\n')

if (process.argv.includes('--check')) {
  const current = existsSync(bundlePath) ? readFileSync(bundlePath, 'utf8') : ''
  if (current !== bundle) {
    console.error('supabase/all_migrations.sql is out of date. Run `npm run db:bundle`.')
    process.exit(1)
  }
  console.log(`all_migrations.sql is up to date (${files.length} migrations).`)
} else {
  writeFileSync(bundlePath, bundle)
  console.log(`Wrote supabase/all_migrations.sql (${files.length} migrations, ${files[0]} … ${files.at(-1)}).`)
}
